// Command table for the Command console (ux.aws.a design 09, section 7): one row per operation of every
// site/api/<service>.openapi.json, generated, so the console's parser and completion read one source and a command can
// only ever name an operation a contract defines.
//
//   node docs/dev.2/gen-commands.mjs            writes site/api/commands.json
//   import { build } from "./gen-commands.mjs"  build(dir) -> the table, for the test that checks the file is current
//
// Row: { command: "<service> <operationId>", service, operationId, global, doc, params: [{ name, pattern? }] (the path
// parameters, in the order the path names them: they are the words after the command), options: [{ name, type }] (the
// query parameters), summary, role (x-role), actions (x-aws-actions) }. Rows sorted by command. No aliases here: design 09
// keeps them in a small hand-kept table that maps only to these commands.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

export function build(dir) {
  const rows = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".openapi.json")).sort()) {
    const doc = JSON.parse(readFileSync(path.join(dir, file), "utf8")), service = file.replace(/\.openapi\.json$/, "");
    const ref = (p) => (p && p.$ref ? p.$ref.replace(/^#\//, "").split("/").reduce((a, k) => a && a[k], doc) : p);
    for (const [route, ops] of Object.entries(doc.paths || {}))
      for (const op of Object.values(ops)) {
        const params = (op.parameters || []).map(ref).filter(Boolean);
        const byName = Object.fromEntries(params.map((p) => [p.name, p]));
        const order = [...route.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]);
        rows.push({
          command: service + " " + op.operationId, service, operationId: op.operationId, global: doc["x-browser-global"], doc: file,
          params: order.map((n) => (byName[n] && byName[n].schema && byName[n].schema.pattern ? { name: n, pattern: byName[n].schema.pattern } : { name: n })),
          options: params.filter((p) => p.in === "query").map((p) => ({ name: p.name, type: (p.schema && (Array.isArray(p.schema.type) ? p.schema.type.join("|") : p.schema.type)) || "string" })),
          summary: op.summary || "", role: op["x-role"] || null, actions: op["x-aws-actions"] || []
        });
      }
  }
  return rows.sort((a, b) => (a.command < b.command ? -1 : a.command > b.command ? 1 : 0));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const dir = new URL("../../site/api/", import.meta.url);
  const rows = build(fileURLToPath(dir));
  writeFileSync(new URL("commands.json", dir), JSON.stringify({ about: "Generated by docs/dev.2/gen-commands.mjs from site/api/*.openapi.json; do not edit by hand.", commands: rows }, null, 2) + "\n");
  console.log("site/api/commands.json: " + rows.length + " commands");
}
